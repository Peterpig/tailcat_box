/** Maps a `ValidationResult.reason` onto a localised sentence. */
export function validationMessage(
  t: Translator,
  base: "transfer.validation.address" | "transfer.validation.remotePath",
  reason: string | undefined,
): string {
  return t(`${base}.${reason ?? "invalid"}`);
}
